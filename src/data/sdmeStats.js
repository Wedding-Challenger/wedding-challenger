// 범위용: 해당 지역에서 유효한 p10(최소)과 p90(최대) 반환
// null이면 가장 가까운 유효값으로 fallback
export function getRange(statsMap, region) {
  const s = statsMap[region] ?? statsMap['전국'];
  const min = s.p10 ?? s.p25 ?? s.mid ?? 0;
  const max = s.p90 ?? s.p75 ?? s.mid ?? 0;
  return { min, max };
}
